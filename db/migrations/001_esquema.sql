-- =====================================================================
-- 001_esquema.sql  ·  Bodegas del Atuel
-- Etapa 1: tipos propios, dominios, tablas, claves primarias y foráneas.
-- Las restricciones adicionales (UNIQUE, CHECK, DEFAULT) se agregan en
-- 002_constraints.sql.
--
-- Decisiones generales (ver docs/01_modelo.md):
--   * Importes en NUMERIC(p,s), nunca FLOAT.
--   * Estados con tipo ENUM (no texto libre).
--   * Claves subrogadas con IDENTITY (BY DEFAULT para permitir la carga
--     masiva con identificadores explícitos y luego ajustar la secuencia).
--   * Claves naturales donde el dato es estable y tiene formato fijo
--     (CUIT, código postal, código de permiso).
--   * ON DELETE RESTRICT en movimientos y entidades con historia (RN-14);
--     ON DELETE CASCADE solo en renglones / entidades débiles que no
--     existen sin su cabecera.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Tipos propios
-- ---------------------------------------------------------------------
CREATE TYPE estado_documento AS ENUM ('en_confeccion', 'terminado', 'procesado');
CREATE TYPE tipo_cliente     AS ENUM ('socio', 'distribuidor', 'exportador');
CREATE TYPE tipo_vino        AS ENUM ('tinto', 'blanco', 'rosado', 'espumante');
CREATE TYPE tipo_cepa        AS ENUM ('tinta', 'blanca');
CREATE TYPE dia_semana       AS ENUM ('lunes', 'martes', 'miercoles', 'jueves',
                                      'viernes', 'sabado', 'domingo');

-- ---------------------------------------------------------------------
-- Dominios
-- ---------------------------------------------------------------------
-- CUIT argentino: exactamente 11 dígitos.
CREATE DOMAIN cuit_dom AS CHAR(11)
    CHECK (VALUE ~ '^[0-9]{11}$');

-- Importe de dinero no negativo.
CREATE DOMAIN dinero_dom AS NUMERIC(14,2)
    CHECK (VALUE >= 0);

-- Porcentaje entre 0 y 100.
CREATE DOMAIN porcentaje_dom AS NUMERIC(5,2)
    CHECK (VALUE BETWEEN 0 AND 100);

-- ---------------------------------------------------------------------
-- Localidades, salas y empleados
-- ---------------------------------------------------------------------
CREATE TABLE localidad (
    codigo_postal       VARCHAR(10)  PRIMARY KEY,
    nombre              VARCHAR(100) NOT NULL,
    provincia           VARCHAR(60)  NOT NULL,
    encargado_regional  VARCHAR(100) NOT NULL   -- RN-02: depende solo de la localidad
);

CREATE TABLE sala_venta (
    id_sala      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calle        VARCHAR(100) NOT NULL,
    numero       VARCHAR(10)  NOT NULL,
    dia_cierre   dia_semana   NOT NULL,
    cp_localidad VARCHAR(10)  NOT NULL
        REFERENCES localidad (codigo_postal) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE empleado (
    cuit          cuit_dom      PRIMARY KEY,
    nombre        VARCHAR(100)  NOT NULL,
    fecha_ingreso DATE          NOT NULL,
    salario       NUMERIC(12,2) NOT NULL,
    id_sala       INTEGER       NOT NULL           -- RN-03: una sola sala, obligatoria
        REFERENCES sala_venta (id_sala) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ---------------------------------------------------------------------
-- Producción de uva
-- ---------------------------------------------------------------------
CREATE TABLE cepa (
    id_cepa INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(50) NOT NULL,
    tipo    tipo_cepa   NOT NULL
);

-- Departamento separado de finca para evitar la dependencia transitiva
-- finca -> departamento -> provincia (3FN).
CREATE TABLE departamento (
    id_departamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(80) NOT NULL,
    provincia       VARCHAR(60) NOT NULL
);

CREATE TABLE finca (
    id_finca        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100)  NOT NULL,
    superficie_ha   NUMERIC(10,2) NOT NULL,
    id_departamento INTEGER       NOT NULL
        REFERENCES departamento (id_departamento) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Entidad débil: no existe sin su finca. Clave (finca, nro_parcela).
CREATE TABLE parcela (
    id_finca        INTEGER       NOT NULL
        REFERENCES finca (id_finca) ON DELETE CASCADE ON UPDATE CASCADE,
    nro_parcela     SMALLINT      NOT NULL,
    superficie_ha   NUMERIC(10,2) NOT NULL,
    anio_plantacion SMALLINT      NOT NULL,
    id_cepa         INTEGER       NOT NULL          -- RN-04: una sola cepa
        REFERENCES cepa (id_cepa) ON DELETE RESTRICT ON UPDATE CASCADE,
    PRIMARY KEY (id_finca, nro_parcela)
);

CREATE TABLE bodega (
    cuit         cuit_dom     PRIMARY KEY,
    razon_social VARCHAR(150) NOT NULL,
    domicilio    VARCHAR(150) NOT NULL
);

CREATE TABLE lote_uva (
    nro_lote         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_finca         INTEGER       NOT NULL,
    nro_parcela      SMALLINT      NOT NULL,
    campania         SMALLINT      NOT NULL,
    fecha_cosecha    DATE          NOT NULL,
    kilos_cosechados NUMERIC(12,2) NOT NULL,
    cuit_bodega      cuit_dom      NOT NULL
        REFERENCES bodega (cuit) ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (id_finca, nro_parcela)
        REFERENCES parcela (id_finca, nro_parcela) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE analisis_calidad (
    id_analisis  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_lote     INTEGER      NOT NULL
        REFERENCES lote_uva (nro_lote) ON DELETE CASCADE ON UPDATE CASCADE,
    fecha        DATE         NOT NULL,
    grado_brix   NUMERIC(4,1) NOT NULL,
    ph           NUMERIC(3,2) NOT NULL,
    acidez_total NUMERIC(4,2) NOT NULL
);

-- ---------------------------------------------------------------------
-- Vinos, composición y maridajes
-- ---------------------------------------------------------------------
CREATE TABLE vino (
    cod_vino    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100)  NOT NULL,
    tipo        tipo_vino     NOT NULL,
    anada       SMALLINT      NOT NULL,
    volumen_ml  INTEGER       NOT NULL,
    graduacion  NUMERIC(4,2)  NOT NULL,
    precio      NUMERIC(12,2) NOT NULL,             -- RN-01: único para toda la red
    cuit_bodega cuit_dom      NOT NULL
        REFERENCES bodega (cuit) ON DELETE RESTRICT ON UPDATE CASCADE   -- RN-14
);

-- N:M con atributo (porcentaje de corte).
CREATE TABLE composicion_vino (
    cod_vino   INTEGER        NOT NULL
        REFERENCES vino (cod_vino) ON DELETE CASCADE ON UPDATE CASCADE,
    id_cepa    INTEGER        NOT NULL
        REFERENCES cepa (id_cepa) ON DELETE RESTRICT ON UPDATE CASCADE,
    porcentaje porcentaje_dom NOT NULL,
    PRIMARY KEY (cod_vino, id_cepa)
);

CREATE TABLE maridaje (
    id_maridaje          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre               VARCHAR(80)  NOT NULL,
    temperatura_servicio NUMERIC(4,1) NOT NULL
);

CREATE TABLE vino_maridaje (
    cod_vino    INTEGER NOT NULL
        REFERENCES vino (cod_vino) ON DELETE CASCADE ON UPDATE CASCADE,
    id_maridaje INTEGER NOT NULL
        REFERENCES maridaje (id_maridaje) ON DELETE RESTRICT ON UPDATE CASCADE,
    PRIMARY KEY (cod_vino, id_maridaje)
);

-- ---------------------------------------------------------------------
-- Clientes: supertipo + subtipos (ver justificación en docs/01_modelo.md)
-- ---------------------------------------------------------------------
CREATE TABLE cliente (
    id_cliente            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_o_razon_social VARCHAR(150)   NOT NULL,
    tipo_doc              VARCHAR(10)    NOT NULL,
    nro_doc               VARCHAR(20)    NOT NULL,
    direccion             VARCHAR(150)   NOT NULL,
    cp_localidad          VARCHAR(10)    NOT NULL
        REFERENCES localidad (codigo_postal) ON DELETE RESTRICT ON UPDATE CASCADE,
    fecha_alta            DATE           NOT NULL,
    tipo_cliente          tipo_cliente   NOT NULL,
    descuento             porcentaje_dom NOT NULL   -- RN-06 (lo completa un trigger)
);

-- Los socios no tienen atributos propios: se identifican por tipo_cliente.
-- Distribuidor y exportador referencian (id_cliente, tipo_cliente) para que
-- un subtipo no pueda colgar de un cliente de otro tipo.
CREATE TABLE distribuidor (
    id_cliente       INTEGER      PRIMARY KEY,
    tipo_cliente     tipo_cliente NOT NULL,
    zona_cobertura   VARCHAR(100) NOT NULL,
    nro_habilitacion VARCHAR(20)  NOT NULL
);

CREATE TABLE exportador (
    id_cliente   INTEGER      PRIMARY KEY,
    tipo_cliente tipo_cliente NOT NULL,
    pais_destino VARCHAR(60)  NOT NULL
);

CREATE TABLE permiso_exportacion (
    cod_permiso       VARCHAR(20) PRIMARY KEY,
    id_cliente        INTEGER     NOT NULL
        REFERENCES exportador (id_cliente) ON DELETE CASCADE ON UPDATE CASCADE,
    fecha_emision     DATE        NOT NULL,
    fecha_vencimiento DATE        NOT NULL
);

-- ---------------------------------------------------------------------
-- Ventas
-- ---------------------------------------------------------------------
CREATE TABLE comprobante (
    nro_comprobante INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha           TIMESTAMP  NOT NULL,
    id_cliente      INTEGER    NOT NULL
        REFERENCES cliente (id_cliente) ON DELETE RESTRICT ON UPDATE CASCADE,
    id_sala         INTEGER    NOT NULL
        REFERENCES sala_venta (id_sala) ON DELETE RESTRICT ON UPDATE CASCADE,
    subtotal        dinero_dom NOT NULL,   -- suma bruta de renglones
    descuento       dinero_dom NOT NULL,   -- importe descontado
    total           dinero_dom NOT NULL    -- RN-08: lo calcula la base
);

CREATE TABLE renglon_comprobante (
    nro_comprobante    INTEGER        NOT NULL
        REFERENCES comprobante (nro_comprobante) ON DELETE CASCADE ON UPDATE CASCADE,
    cod_vino           INTEGER        NOT NULL
        REFERENCES vino (cod_vino) ON DELETE RESTRICT ON UPDATE CASCADE,
    cantidad           INTEGER        NOT NULL,
    precio_unitario    NUMERIC(12,2)  NOT NULL,   -- precio al momento de la venta
    descuento_aplicado porcentaje_dom NOT NULL,   -- % según tipo de cliente
    subtotal           dinero_dom     NOT NULL,
    PRIMARY KEY (nro_comprobante, cod_vino)
);

-- ---------------------------------------------------------------------
-- Stock
-- ---------------------------------------------------------------------
CREATE TABLE stock_sala (
    id_sala  INTEGER NOT NULL
        REFERENCES sala_venta (id_sala) ON DELETE RESTRICT ON UPDATE CASCADE,
    cod_vino INTEGER NOT NULL
        REFERENCES vino (cod_vino) ON DELETE RESTRICT ON UPDATE CASCADE,
    cantidad INTEGER NOT NULL,
    PRIMARY KEY (id_sala, cod_vino)
);

-- Un único depósito central: una fila por vino.
CREATE TABLE stock_deposito (
    cod_vino INTEGER PRIMARY KEY
        REFERENCES vino (cod_vino) ON DELETE RESTRICT ON UPDATE CASCADE,
    cantidad INTEGER NOT NULL
);

-- ---------------------------------------------------------------------
-- Transporte, ingresos y transferencias
-- ---------------------------------------------------------------------
CREATE TABLE transportista (
    codigo_transporte INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social      VARCHAR(150) NOT NULL,
    cuit              cuit_dom     NOT NULL,
    email             VARCHAR(120) NOT NULL,
    telefono          VARCHAR(30)  NOT NULL,
    domicilio         VARCHAR(150) NOT NULL
);

CREATE TABLE transportista_localidad (
    codigo_transporte INTEGER     NOT NULL
        REFERENCES transportista (codigo_transporte) ON DELETE CASCADE ON UPDATE CASCADE,
    cp_localidad      VARCHAR(10) NOT NULL
        REFERENCES localidad (codigo_postal) ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (codigo_transporte, cp_localidad)
);

CREATE TABLE ingreso (
    codigo_ingreso    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha             DATE             NOT NULL,
    estado            estado_documento NOT NULL,
    codigo_transporte INTEGER          NOT NULL
        REFERENCES transportista (codigo_transporte) ON DELETE RESTRICT ON UPDATE CASCADE,  -- RN-14
    cuit_bodega       cuit_dom         NOT NULL
        REFERENCES bodega (cuit) ON DELETE RESTRICT ON UPDATE CASCADE                       -- RN-14
);

CREATE TABLE renglon_ingreso (
    codigo_ingreso INTEGER NOT NULL
        REFERENCES ingreso (codigo_ingreso) ON DELETE CASCADE ON UPDATE CASCADE,
    cod_vino       INTEGER NOT NULL
        REFERENCES vino (cod_vino) ON DELETE RESTRICT ON UPDATE CASCADE,
    cantidad       INTEGER NOT NULL,
    PRIMARY KEY (codigo_ingreso, cod_vino)
);

CREATE TABLE transferencia (
    nro_transferencia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sala           INTEGER          NOT NULL
        REFERENCES sala_venta (id_sala) ON DELETE RESTRICT ON UPDATE CASCADE,
    fecha_confeccion  DATE             NOT NULL,
    estado            estado_documento NOT NULL
);

CREATE TABLE renglon_transferencia (
    nro_transferencia INTEGER NOT NULL
        REFERENCES transferencia (nro_transferencia) ON DELETE CASCADE ON UPDATE CASCADE,
    cod_vino          INTEGER NOT NULL
        REFERENCES vino (cod_vino) ON DELETE RESTRICT ON UPDATE CASCADE,
    cantidad          INTEGER NOT NULL,
    PRIMARY KEY (nro_transferencia, cod_vino)
);

-- ---------------------------------------------------------------------
-- Auditoría de precios (RN-13). La completa un trigger.
-- ---------------------------------------------------------------------
CREATE TABLE auditoria_precio (
    id_auditoria    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_vino        INTEGER       NOT NULL
        REFERENCES vino (cod_vino) ON DELETE RESTRICT ON UPDATE CASCADE,
    precio_anterior NUMERIC(12,2) NOT NULL,
    precio_nuevo    NUMERIC(12,2) NOT NULL,
    fecha_hora      TIMESTAMPTZ   NOT NULL,
    usuario         VARCHAR(63)   NOT NULL
);

-- ---------------------------------------------------------------------
-- Descripción de cada tabla (queda en el catálogo y alimenta el
-- diccionario de datos: docs/02_diccionario_datos.md)
-- ---------------------------------------------------------------------
COMMENT ON TABLE localidad IS 'Localidades de Mendoza (catálogo real). El encargado regional depende solo de la localidad (RN-02).';
COMMENT ON TABLE sala_venta IS 'Salas de venta de la red; cada una en una localidad y con un día de cierre semanal.';
COMMENT ON TABLE empleado IS 'Empleados; cada uno trabaja en una única sala (RN-03).';
COMMENT ON TABLE cepa IS 'Catálogo de cepas (variedades de uva), tintas o blancas.';
COMMENT ON TABLE departamento IS 'Departamentos de la provincia donde se ubican las fincas.';
COMMENT ON TABLE finca IS 'Fincas productoras de uva.';
COMMENT ON TABLE parcela IS 'Entidad débil de finca: se identifica por (finca, número de parcela); tiene una cepa plantada.';
COMMENT ON TABLE bodega IS 'Bodegas elaboradoras (clave natural: CUIT).';
COMMENT ON TABLE lote_uva IS 'Lote cosechado en una parcela en una campaña y entregado a una bodega (RN-04).';
COMMENT ON TABLE analisis_calidad IS 'Análisis de laboratorio de un lote (grado Brix, pH, acidez).';
COMMENT ON TABLE vino IS 'Vinos del catálogo. El precio es único para toda la red (RN-01).';
COMMENT ON TABLE composicion_vino IS 'Corte del vino: porcentaje de cada cepa; la suma debe ser 100 (RN-05).';
COMMENT ON TABLE maridaje IS 'Catálogo de comidas sugeridas con su temperatura de servicio.';
COMMENT ON TABLE vino_maridaje IS 'Relación N:M entre vinos y maridajes.';
COMMENT ON TABLE cliente IS 'Supertipo de clientes (socio, distribuidor, exportador). El descuento lo asigna un trigger según el tipo (RN-06).';
COMMENT ON TABLE distribuidor IS 'Subtipo de cliente: zona de cobertura y número de habilitación.';
COMMENT ON TABLE exportador IS 'Subtipo de cliente: país de destino.';
COMMENT ON TABLE permiso_exportacion IS 'Permisos de un exportador; vencimiento posterior a la emisión (RN-07).';
COMMENT ON TABLE comprobante IS 'Cabecera de venta. Subtotal, descuento y total los calcula la base (RN-08).';
COMMENT ON TABLE renglon_comprobante IS 'Renglón de venta: guarda precio y descuento del momento; descuenta stock de la sala (RN-09).';
COMMENT ON TABLE stock_sala IS 'Stock de cada vino en cada sala; nunca negativo (RN-09).';
COMMENT ON TABLE stock_deposito IS 'Stock del depósito central (uno solo); nunca negativo.';
COMMENT ON TABLE transportista IS 'Empresas de transporte que trasladan los ingresos.';
COMMENT ON TABLE transportista_localidad IS 'Localidades que cubre cada transportista (N:M).';
COMMENT ON TABLE ingreso IS 'Ingreso de botellas desde una bodega al depósito (en_confeccion -> terminado -> procesado, RN-10).';
COMMENT ON TABLE renglon_ingreso IS 'Vinos y cantidades de un ingreso; solo editables en confección (RN-12).';
COMMENT ON TABLE transferencia IS 'Transferencia del depósito a una sala (en_confeccion -> terminado -> procesado, RN-11).';
COMMENT ON TABLE renglon_transferencia IS 'Vinos y cantidades de una transferencia; solo editables en confección (RN-12).';
COMMENT ON TABLE auditoria_precio IS 'Historial de cambios de precio de vinos, lo completa un trigger (RN-13).';
